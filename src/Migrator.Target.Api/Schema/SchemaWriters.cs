using System.Text;

namespace Migrator.Target.Api.Schema;

/// <summary>Writes the inferred structure: a T-SQL script (idempotent, batches separated by `GO`) and a report that shows the evidence behind every table.</summary>
public static class SchemaWriters
{
    public static string Ddl(DbSchema schema)
    {
        var sb = new StringBuilder();
        sb.AppendLine("-- Generated by Migrator.Target.Api from the SQL text of the application's data-access code.");
        sb.AppendLine("-- INFERRED structure: types, keys and nullability are guesses (see SCHEMA_REPORT.md). Review before using it for real data.");
        sb.AppendLine("-- Idempotent: every table is created only when it does not exist. Batches are separated by GO.");
        sb.AppendLine();
        foreach (var t in schema.Tables)
        {
            sb.AppendLine($"IF OBJECT_ID(N'dbo.{t.Name}', N'U') IS NULL");
            sb.AppendLine("BEGIN");
            sb.AppendLine($"    CREATE TABLE dbo.[{t.Name}] (");
            var lines = new List<string>();
            foreach (var c in t.Columns)
            {
                if (c.IsSurrogate) lines.Add($"        [{c.Name}] int IDENTITY(1,1) NOT NULL CONSTRAINT [PK_{t.Name}] PRIMARY KEY");
                else if (c.IsKey) lines.Add($"        [{c.Name}] {c.SqlType} NOT NULL CONSTRAINT [PK_{t.Name}] PRIMARY KEY");
                else lines.Add($"        [{c.Name}] {c.SqlType} NULL");
            }
            sb.AppendLine(string.Join(",\n", lines));
            sb.AppendLine("    );");
            sb.AppendLine("END");
            sb.AppendLine("GO");
        }
        foreach (var r in schema.Relations.Where(r => schema.Tables.Any(t => t.Name == r.Table && t.Find(r.Column) is { IsKey: false })))
        {
            sb.AppendLine($"IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_{r.Table}_{r.Column}' AND object_id = OBJECT_ID(N'dbo.{r.Table}'))");
            sb.AppendLine($"    CREATE INDEX [IX_{r.Table}_{r.Column}] ON dbo.[{r.Table}] ([{r.Column}]);");
            sb.AppendLine("GO");
        }
        return sb.ToString();
    }

    public static string Report(DbSchema schema, bool repositories, string? note)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Schema report — inferred from SQL");
        sb.AppendLine();
        var columns = schema.Tables.Sum(t => t.Columns.Count(c => !c.IsSurrogate));
        var evidence = schema.Tables.Sum(t => t.Columns.Count(c => c.TypeIsEvidence));
        sb.AppendLine($"- **{schema.Tables.Count}** table(s), **{columns}** column(s) seen in SQL text; **{evidence}** column type(s) backed by the C# type of a value the code writes, the rest from name hints or the default.");
        sb.AppendLine($"- **{schema.Tables.Count(t => t.KeyIsSurrogate)}** table(s) have no key evidence and got an identity column (`RowId`); **{schema.Tables.Count(t => !t.KeyIsSurrogate)}** have a key from `select max(col) + 1`.");
        sb.AppendLine($"- **{schema.Relations.Count}** join relation(s) found (indexes only; no foreign keys are created, because the original code does not insert in a guaranteed parent-first order).");
        sb.AppendLine($"- Repositories (`Data/Repositories`, `/api/data/<table>`): {(repositories ? "generated" : "not generated (needs the sqlclient provider)")}.");
        if (note is not null) sb.AppendLine($"- {note}");
        sb.AppendLine();
        sb.AppendLine("This is a **reconstruction**, not the original database: columns the code never names in SQL are missing, `select *` tables show only the columns other statements mention, and every type is a guess. `schema.sql` creates it on an empty LocalDB or SQL Server; compare it with the real database before trusting it.");
        sb.AppendLine();
        sb.AppendLine("## Tables");
        foreach (var t in schema.Tables)
        {
            sb.AppendLine();
            sb.AppendLine($"### {t.Name}{(t.LooksLikeWorkTable ? "  — report work table (emptied, then refilled by INSERT ... SELECT)" : "")}");
            sb.AppendLine();
            sb.AppendLine($"Key: `{t.KeyColumn}` — {t.KeyReason}. Used by: {string.Join(", ", t.UsedBy.Take(6).Select(u => $"`{u}`"))}{(t.UsedBy.Count > 6 ? $" and {t.UsedBy.Count - 6} more" : "")}.");
            sb.AppendLine();
            sb.AppendLine("| Column | Type | Basis |");
            sb.AppendLine("|---|---|---|");
            foreach (var c in t.Columns) sb.AppendLine($"| {c.Name}{(c.IsKey ? " (key)" : "")} | {c.SqlType} | {(c.TypeIsEvidence ? "evidence: " : "inferred: ")}{c.TypeReason} |");
        }
        if (schema.Relations.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("## Relations (from JOIN / WHERE comparisons)");
            sb.AppendLine();
            foreach (var r in schema.Relations) sb.AppendLine($"- `{r.Table}.{r.Column}` -> `{r.ReferencedTable}.{r.ReferencedColumn}` (seen in `{r.Where}`)");
        }
        return sb.ToString();
    }
}
