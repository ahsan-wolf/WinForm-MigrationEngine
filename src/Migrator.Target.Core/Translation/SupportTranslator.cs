using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using WebFormsMigrator.IR.Models;

namespace Migrator.Target.Core.Translation;

/// <summary>
/// Emits the project's own non-UI classes (static helper modules, data classes, enums) as one TypeScript module, <c>src/support/index.ts</c>:
/// enums become `export enum`, classes become `export class` with static/instance members, translated by the same rules as page methods.
/// Everything that cannot be translated stays a commented original behind a typed stub, so pages can still call and import it.
/// </summary>
internal static class SupportTranslator
{
    public const string ModulePath = "src/support/index.ts";

    public static SupportModule Emit(SupportRegistry registry, TranslationEnv env, ISet<string> demoted)
    {
        var output = new PageTranslation { FixturesImport = env.Vocabulary.FixturesImport };
        var module = new SupportModule { Classes = registry.Classes.Count };
        var lines = new List<string>();
        var ranges = new List<(string Key, int Start, int End)>();

        foreach (var cls in Ordered(registry))
        {
            var scope = new PageScope
            {
                RootId = "",
                IsModule = true,
                OwnerName = cls.Name,
                Vocabulary = env.Vocabulary,
                Components = env.Components,
                Units = env.Units,
                Generated = env.Generated,
                Support = registry.Classes,
                Bypass = env.Bypass,
                ServerBound = env.ServerBound,
                Output = output
            };
            foreach (var f in cls.Fields.Values) scope.Fields.TryAdd(f.Name, f);
            foreach (var (name, fns) in cls.Functions) scope.Functions[name] = fns;

            if (cls.IsEnum) EmitEnum(cls, scope, lines);
            else EmitClass(cls, scope, lines, ranges, module, demoted);
        }

        // Imports are decided from the code that is actually emitted (a stubbed method must not leave an unused import).
        var code = PageTranslator.StripStrings(string.Join("\n", lines.Where(l => !l.TrimStart().StartsWith("//", StringComparison.Ordinal))));
        var header = new List<string>
        {
            "// Generated by Migrator.Target.React from the project's own non-UI classes (support.ir.json). Not final: see MIGRATION_REPORT.md.",
            "// Static classes keep their name and members, so translated pages call them as in the original (main.GetImageListKey(...))."
        };
        if (env.Vocabulary.InstanceName.Length > 0 && env.Vocabulary.ServiceImport.Length > 0 && Regex.IsMatch(code, $@"\b{Regex.Escape(env.Vocabulary.InstanceName)}\."))
            header.Add(env.Vocabulary.ServiceImport.StartsWith("import", StringComparison.Ordinal) ? env.Vocabulary.ServiceImport : $"import {{ {env.Vocabulary.InstanceName} }} from '{env.Vocabulary.ServiceImport}';");
        var typeImports = output.TypeImports.Where(t => Regex.IsMatch(code, $@"(?<![\w.]){Regex.Escape(t)}\b")).ToList();
        if (typeImports.Count > 0) header.Add($"import type {{ {string.Join(", ", typeImports)} }} from '{env.Vocabulary.TypesImport}';");
        if (Regex.IsMatch(code, @"\bfixtures\.") && output.FixturesImport.Length > 0) header.Add($"import {{ fixtures }} from '{output.FixturesImport}';");
        var csharpHelpers = CsharpRuntime.Helpers.Where(h => Regex.IsMatch(code, $@"\b{h}\(")).ToList();
        if (csharpHelpers.Count > 0) header.Add($"import {{ {string.Join(", ", csharpHelpers)} }} from '../lib/csharp';");
        var uiImports = new List<string>();
        if (Regex.IsMatch(code, @"\bWfListItem\b")) uiImports.Add("type WfListItem");
        if (Regex.IsMatch(code, @"\bWfTreeNode\b")) uiImports.Add("type WfTreeNode");
        foreach (var helper in new[] { "wfListItem", "wfListItemFromArray", "wfTreeNode", "wfSetExpanded", "wfSetItemChecked" }) if (Regex.IsMatch(code, $@"\b{helper}\(")) uiImports.Add(helper);
        if (uiImports.Count > 0) header.Add($"import {{ {string.Join(", ", uiImports)} }} from '{env.UiLibraryPackage}';");
        header.Add("");

        foreach (var r in ranges) module.Ranges.Add((r.Key, r.Start + header.Count, r.End + header.Count));
        module.Source = string.Join("\n", header.Concat(lines)) + "\n";
        return module;
    }

    /// <summary>Enums first, then classes so that a static initializer never reads a class that is defined later (module-evaluation order).</summary>
    private static List<SupportClassInfo> Ordered(SupportRegistry registry)
    {
        var result = new List<SupportClassInfo>();
        var state = new Dictionary<string, int>(StringComparer.Ordinal);

        void Visit(SupportClassInfo cls)
        {
            if (state.TryGetValue(cls.Name, out _)) return;
            state[cls.Name] = 1;
            if (BaseOf(cls, registry.Classes) is { } baseClass) Visit(baseClass); // `class A extends B` evaluates B when A is defined
            // Everything that can run while the module loads: static initializers, and (because a static initializer may construct an instance)
            // instance field initializers and constructor bodies of every class. Method bodies run later and do not constrain the order.
            var initText = string.Join("\n", cls.Ir.Members
                .Where(m => m.Kind is MemberKind.Field or MemberKind.Property || m.Name == ".ctor")
                .Select(m => m.Type + " " + m.Body));
            foreach (var other in registry.Classes.Values)
                if (other.Name != cls.Name && Regex.IsMatch(initText, $@"\b{Regex.Escape(other.Name)}\b")) Visit(other);
            result.Add(cls);
        }

        foreach (var cls in registry.Classes.Values.Where(c => c.IsEnum)) Visit(cls);
        foreach (var cls in registry.Classes.Values) Visit(cls);
        return result;
    }

    private static string Member(string name) => name;

    /// <summary>The support class a class derives from (generated as `extends`), or null when its base is not a project class or would be a cycle.</summary>
    private static SupportClassInfo? BaseOf(SupportClassInfo cls, IReadOnlyDictionary<string, SupportClassInfo> classes)
    {
        if (cls.IsEnum || cls.Ir.IsStatic || cls.Ir.BaseType is not { } text) return null;
        var simple = text.Contains('<') ? text[..text.IndexOf('<')] : text;
        simple = simple[(simple.LastIndexOf('.') + 1)..];
        if (!classes.TryGetValue(simple, out var baseClass) || baseClass.IsEnum || baseClass.Ir.IsStatic || baseClass.Name == cls.Name) return null;
        for (var up = baseClass; up is not null; up = BaseOf(up, classes))   // a cycle in the declared bases is not extendable
            if (up.Name == cls.Name) return null;
        return baseClass;
    }

    private static void EmitEnum(SupportClassInfo cls, PageScope scope, List<string> lines)
    {
        lines.Add($"export enum {cls.Name} {{");
        foreach (var v in cls.Ir.EnumValues)
        {
            string? value = null;
            if (v.Value is not null)
            {
                try { value = new MethodTranslator(scope, null, constantContext: true).TranslateConstant(v.Value); }
                catch (Untranslatable) { }
            }
            lines.Add($"  {Member(v.Name)}{(value is null ? "" : $" = {value}")},");
        }
        lines.Add("}");
        lines.Add("");
    }

    private static void EmitClass(SupportClassInfo cls, PageScope scope, List<string> lines, List<(string Key, int Start, int End)> ranges,
        SupportModule module, ISet<string> demoted)
    {
        if (cls.Ir.External) { EmitShape(cls, scope, lines, module); return; }

        var baseClass = BaseOf(cls, scope.Support);
        if (baseClass is null && cls.Ir.BaseType is { } baseType && baseType != "object")
            lines.Add($"// {cls.Name} derives from {baseType}: the base type is not generated.");
        foreach (var u in cls.Ir.Unsupported) lines.Add($"// TODO: not extracted — {u}");
        lines.Add($"export class {cls.Name}{(baseClass is null ? "" : $" extends {baseClass.Name}")} {{");

        // A field or property the base chain already declares stays the base's (C# member hiding cannot be expressed: a different type is a TypeScript error).
        var inheritedData = new HashSet<string>(StringComparer.Ordinal);
        for (var up = baseClass; up is not null; up = BaseOf(up, scope.Support)) inheritedData.UnionWith(up.Fields.Keys);

        foreach (var m in cls.Ir.Members.Where(m => m.Kind is MemberKind.Field or MemberKind.Property))
        {
            if (inheritedData.Contains(m.Name)) { lines.Add($"  // {m.Name}: redeclares a member of the base class; the base's declaration is kept"); continue; }
            if (m.Attributes.Contains("mod:accessors")) EmitAccessors(cls, m, scope, lines, ranges, module, demoted);
            else EmitField(cls, m, scope, lines);
        }

        EmitConstructor(cls, scope, lines, ranges, module, demoted);

        foreach (var (name, overloads) in cls.Functions)
            foreach (var fn in overloads)
                EmitMethod(cls, fn, scope, lines, ranges, module, demoted, scope.ServerBound);

        lines.Add("}");
        lines.Add("");
    }

    /// <summary>
    /// A class of a referenced library project: its API shape only. Fields and properties are typed fields, methods are typed stubs that accept any arguments,
    /// the constructor accepts any arguments. Nothing of its code is translated (it is a library, and it may be a large generated layer).
    /// </summary>
    private static void EmitShape(SupportClassInfo cls, PageScope scope, List<string> lines, SupportModule module)
    {
        var baseClass = BaseOf(cls, scope.Support);
        lines.Add($"// {cls.Name}: library class ({cls.Ir.RelativePath}) — API shape only, not translated.");
        lines.Add($"export class {cls.Name}{(baseClass is null ? "" : $" extends {baseClass.Name}")} {{");

        // Members the base chain already declares are inherited as they are: redeclaring one with a slightly different type is a TypeScript error.
        var inherited = new HashSet<string>(StringComparer.Ordinal);
        for (var up = BaseOf(cls, scope.Support); up is not null; up = BaseOf(up, scope.Support))
        {
            inherited.UnionWith(up.Fields.Keys);
            inherited.UnionWith(up.Functions.Values.SelectMany(f => f).Select(f => f.TsName));
        }

        foreach (var m in cls.Ir.Members.Where(m => m.Kind is MemberKind.Field or MemberKind.Property && !inherited.Contains(m.Name)))
        {
            var ts = scope.Vocabulary.MapType(m.Type, scope.Output.TypeImports);
            lines.Add($"  {(m.IsStatic ? "static " : "")}{Member(m.Name)}: {ts} = {ShapeDefault(scope, m, ts)};");
        }

        if (baseClass is not null || cls.Constructors.Any(c => c.Parameters.Count > 0))
            lines.Add($"  constructor(..._args: unknown[]) {{{(baseClass is null ? "" : " super();")} }}");

        foreach (var (_, overloads) in cls.Functions)
            foreach (var fn in overloads.Where(f => !inherited.Contains(f.TsName)))
            {
                var ret = scope.Vocabulary.MapType(fn.Member.Type, scope.Output.TypeImports);
                var returns = PageTranslator.DefaultReturn(scope, fn.Member);
                lines.Add($"  {(fn.Member.IsStatic ? "static " : "")}{Member(fn.TsName)}(..._args: unknown[]){(fn.Member.Type == "void" ? "" : $": {ret}")} {{ {returns} }}");
            }

        lines.Add("}");
        lines.Add("");
    }

    /// <summary>Default of a shape field: primitives and empty collections, never an object (entity graphs are cyclic, so `new T()` fields would recurse).</summary>
    private static string ShapeDefault(PageScope scope, MemberIr m, string ts)
    {
        var d = PageTranslator.FieldInitial(scope, new MemberIr { Type = m.Type, Name = m.Name });
        return d.StartsWith("new ", StringComparison.Ordinal) || d.StartsWith("Object.create(", StringComparison.Ordinal) ? $"null as unknown as {ts}" : d;
    }

    // --------------------------------------------------------------------------------------------------- fields

    private static void EmitField(SupportClassInfo cls, MemberIr m, PageScope scope, List<string> lines)
    {
        var ts = scope.Vocabulary.MapType(m.Type, scope.Output.TypeImports);
        var init = Initial(scope, m, ts, out var mock);
        if (mock) lines.Add($"  // MOCK — {m.Name} starts with sample data; replace with real implementation (inferred — check against backend contract)");
        var modifiers = (m.IsStatic ? "static " : "") + (m.Attributes.Contains("mod:const") ? "readonly " : "");
        lines.Add($"  {modifiers}{Member(m.Name)}: {ts} = {init};");
    }

    /// <summary>Initial value: the translated initializer, else sample data for contract types, else a default for the declared type.</summary>
    private static string Initial(PageScope scope, MemberIr m, string ts, out bool mock)
    {
        mock = false;
        if (!string.IsNullOrWhiteSpace(m.Body))
        {
            try
            {
                var constant = new MethodTranslator(scope, null, constantContext: true).TranslateConstant(m.Body!);
                if (constant is "[]" or "{}" && !ts.Contains("unknown")) return $"{constant} as {ts}";
                if (constant == "null")
                {
                    if (ts == "unknown") return "undefined as unknown";
                    // `null` means "not set yet" in the desktop app (no user logged in); a browser mock needs a usable object so member reads do not throw.
                    if (scope.Support.TryGetValue(ts, out var supportType) && !supportType.IsEnum && !supportType.Ir.IsStatic)
                    {
                        mock = true;
                        return PageTranslator.SupportDefault(supportType, ts);
                    }
                    var sample = PageTranslator.MockDefault(scope, m.Type, ts, scope.Output.FixturesImport.Length > 0);
                    if (sample is not null && sample.StartsWith("fixtures.", StringComparison.Ordinal)) { mock = true; return sample; }
                    return $"null as unknown as {ts}";
                }
                return constant;
            }
            catch (Untranslatable)
            {
                // fall through: a typed default keeps every reference compiling
            }
        }

        var fixture = PageTranslator.MockDefault(scope, m.Type, ts, scope.Output.FixturesImport.Length > 0);
        if (fixture is not null && fixture.StartsWith("fixtures.", StringComparison.Ordinal)) { mock = true; return fixture; }
        var fallback = PageTranslator.FieldInitial(scope, new MemberIr { Type = m.Type, Name = m.Name });
        // A static field may be a ready-made instance (`new T()`), but an instance field must not (object graphs can be cyclic: construction would never end).
        return !m.IsStatic && (fallback.StartsWith("new ", StringComparison.Ordinal) || fallback.StartsWith("Object.create(", StringComparison.Ordinal)) ? $"null as unknown as {ts}" : fallback;
    }

    // ----------------------------------------------------------------------------------------------- accessors

    private static void EmitAccessors(SupportClassInfo cls, MemberIr m, PageScope scope, List<string> lines, List<(string Key, int Start, int End)> ranges,
        SupportModule module, ISet<string> demoted)
    {
        var ts = scope.Vocabulary.MapType(m.Type, scope.Output.TypeImports);
        var tree = CSharpSyntaxTree.ParseText("class __W { " + m.Type + " P " + m.Body + " }");
        var property = tree.GetRoot().DescendantNodes().OfType<PropertyDeclarationSyntax>().FirstOrDefault();
        if (property?.AccessorList is null) { lines.Add($"  // TODO: not translated — property {m.Name}"); return; }

        var prefix = m.IsStatic ? "static " : "";
        foreach (var accessor in property.AccessorList.Accessors)
        {
            var isGet = accessor.Keyword.IsKind(SyntaxKind.GetKeyword);
            var bodyText = accessor.Body?.ToString() ?? "{ }";
            var key = $"{cls.Name}.{m.Name}.{(isGet ? "get" : "set")}";
            var member = new MemberIr
            {
                Kind = MemberKind.Method, Name = key, Type = isGet ? m.Type : "void", Body = bodyText, IsStatic = m.IsStatic,
                Parameters = isGet ? new List<ParameterIr>() : new List<ParameterIr> { new() { Name = "value", Type = m.Type } }
            };
            var translation = TranslateBody(scope, member, demoted.Contains(key), allowAwait: false, out var body, out var stub);
            module.Methods.Add(translation);

            var start = lines.Count;
            lines.Add(isGet ? $"  {prefix}get {Member(m.Name)}(): {ts} {{" : $"  {prefix}set {Member(m.Name)}(value: {ts}) {{");
            if (stub) AddStub(lines, member, scope, indent: "    ", defaultReturn: isGet);
            else lines.AddRange(body.Select(l => l.Length == 0 ? l : "    " + l));
            lines.Add("  }");
            ranges.Add((key, start + 1, lines.Count));
        }
    }

    // ------------------------------------------------------------------------------------------ constructors

    private static void EmitConstructor(SupportClassInfo cls, PageScope scope, List<string> lines, List<(string Key, int Start, int End)> ranges,
        SupportModule module, ISet<string> demoted)
    {
        var ctors = cls.Constructors.Where(c => c.Body != null).ToList();
        if (ctors.Count == 0 || cls.Ir.IsStatic) return;

        var chosen = ctors.OrderByDescending(c => c.Parameters.Count).First();
        var min = ctors.Min(c => c.Parameters.Count(p => p.DefaultValue == null));
        if (ctors.Count > 1) module.Notes.Add($"{cls.Name}: {ctors.Count} constructors merged into one (the longest); parameters beyond {min} are optional");

        // Parameters beyond the shortest overload become optional.
        var shaped = new MemberIr
        {
            Kind = MemberKind.Method, Name = $"{cls.Name}.constructor", Type = "void", Body = chosen.Body,
            Parameters = chosen.Parameters.Select((p, i) => new ParameterIr { Name = p.Name, Type = StripRef(p.Type), DefaultValue = p.DefaultValue ?? (i >= min ? "null!" : null) }).ToList()
        };
        var key = $"{cls.Name}.constructor";
        var translation = TranslateBody(scope, shaped, demoted.Contains(key), allowAwait: false, out var body, out var stub, translationKey: key);
        if (chosen.Parameters.Any(p => IsByRef(p.Type))) { stub = true; translation.Reasons.Add("ref/out parameter"); translation.Status = TranslationStatus.NotTranslated; }
        module.Methods.Add(translation);

        var bodyText = string.Join("\n", body.Where(l => !l.TrimStart().StartsWith("//", StringComparison.Ordinal)));
        var parameters = PageTranslator.Params(scope, shaped, new MemberFunction { Member = shaped, TsName = "constructor" }, bodyText);
        var start = lines.Count;
        lines.Add($"  constructor({parameters}) {{");
        if (BaseOf(cls, scope.Support) is { } ctorBase)
        {
            // A derived constructor starts with super(...): the base constructor's required parameters get placeholders (the original base(...) call is not extracted).
            var required = ctorBase.Constructors.Select(c => c.Parameters.Count(x => x.DefaultValue == null)).DefaultIfEmpty(0).Min();
            lines.Add($"    super({string.Join(", ", Enumerable.Repeat("null!", required))});");
        }
        if (stub) AddStub(lines, shaped, scope, indent: "    ", defaultReturn: false);
        else lines.AddRange(body.Select(l => l.Length == 0 ? l : "    " + l));
        lines.Add("  }");
        ranges.Add((key, start + 1, lines.Count));
    }

    // ----------------------------------------------------------------------------------------------- methods

    private static void EmitMethod(SupportClassInfo cls, MemberFunction fn, PageScope scope, List<string> lines, List<(string Key, int Start, int End)> ranges,
        SupportModule module, ISet<string> demoted, ServerBoundRules serverRules)
    {
        var m = fn.Member;
        if (m.Body is null) return;

        var key = $"{cls.Name}.{fn.TsName}";
        var byRef = m.Parameters.Any(p => IsByRef(p.Type));
        var shaped = new MemberIr
        {
            Kind = MemberKind.Method, Name = m.Name, Type = m.Type, Body = m.Body, IsStatic = m.IsStatic,
            Parameters = m.Parameters.Select(p => new ParameterIr { Name = p.Name, Type = StripRef(p.Type), DefaultValue = p.DefaultValue }).ToList()
        };
        var serverMarker = serverRules.Match(m.Body);
        var translation = TranslateBody(scope, shaped, demoted.Contains(key) || byRef || serverMarker is not null, allowAwait: fn.IsAsync, out var body, out var stub, translationKey: key,
            demotedLines: LineDemotion.For(demoted, key), stubReason: serverMarker is not null ? $"server-side code (uses {serverMarker}): needs the backend" : null);
        if (byRef) translation.Reasons.Add("ref/out parameter (the generated signature takes the value only)");
        translation.IsAsync = fn.IsAsync;
        module.Methods.Add(translation);

        var bodyText = string.Join("\n", body.Where(l => !l.TrimStart().StartsWith("//", StringComparison.Ordinal)));
        var parameters = PageTranslator.Params(scope, shaped, fn, bodyText);
        var start = lines.Count;
        if (translation.Status == TranslationStatus.Partial) lines.Add($"  // TODO: partially translated — {translation.Todos} statement(s) need manual work");
        lines.Add($"  {(m.IsStatic ? "static " : "")}{(fn.IsAsync ? "async " : "")}{Member(fn.TsName)}({parameters}) {{");
        if (stub) AddStub(lines, shaped, scope, indent: "    ", defaultReturn: true);
        else lines.AddRange(body.Select(l => l.Length == 0 ? l : "    " + l));
        lines.Add("  }");
        ranges.Add((key, start + 1, lines.Count));
    }

    // -------------------------------------------------------------------------------------------------- shared

    private static MethodTranslation TranslateBody(PageScope scope, MemberIr member, bool forceStub, bool allowAwait, out List<string> body, out bool stub, string? translationKey = null, string? stubReason = null, IReadOnlySet<int>? demotedLines = null)
    {
        var translation = new MethodTranslation { Member = member, TsName = translationKey ?? member.Name };
        body = new List<string>();
        stub = false;
        if (forceStub)
        {
            translation.Reasons.Add(stubReason ?? "demoted by the TypeScript compile gate");
            translation.Todos = 1;
            translation.Status = TranslationStatus.NotTranslated;
            stub = true;
            return translation;
        }

        var translator = new MethodTranslator(scope, member);
        body = translator.TranslateBody(out var top, out var fallbacks);
        body = PageTranslator.RenameUnusedLocals(body);   // addresses of demoted statements index this first-emission body
        body = LineDemotion.Apply(body, demotedLines ?? new HashSet<int>(), out var demotedCount);
        if (demotedCount > 0) { translation.Reasons.Add("statement fails the TypeScript check"); body = PageTranslator.RenameUnusedLocals(body, merge: false); }
        translation.Todos = translator.Todos + demotedCount;
        translation.Reasons.AddRange(translator.Reasons);
        translation.Bypasses.AddRange(translator.Bypasses);

        // `await` is only legal in an async method; constructors and accessors cannot be async, so they fall back.
        if (!allowAwait && body.Any(l => !l.TrimStart().StartsWith("//", StringComparison.Ordinal) && Regex.IsMatch(l, @"\bawait\b")))
        {
            translation.Reasons.Add("needs an asynchronous call, which a constructor or property accessor cannot make");
            translation.Todos = Math.Max(translation.Todos, 1);
            translation.Status = TranslationStatus.NotTranslated;
            stub = true;
            return translation;
        }

        var allFellBack = top > 0 && fallbacks == top && body.All(l => l.TrimStart().StartsWith("//", StringComparison.Ordinal));
        translation.Status = allFellBack ? TranslationStatus.NotTranslated : translation.Todos > 0 ? TranslationStatus.Partial : TranslationStatus.Complete;
        stub = translation.Status == TranslationStatus.NotTranslated;
        return translation;
    }

    private static void AddStub(List<string> lines, MemberIr m, PageScope scope, string indent, bool defaultReturn)
    {
        lines.Add($"{indent}// TODO: not translated — original C# is in the project source ({m.Name}) and below");
        foreach (var l in (m.Body ?? "").Split('\n')) lines.Add($"{indent}// {l.TrimEnd('\r')}");
        if (defaultReturn && PageTranslator.DefaultReturn(scope, m) is { } fallback) lines.Add($"{indent}{fallback}");
    }

    private static bool IsByRef(string type) => type.StartsWith("ref ", StringComparison.Ordinal) || type.StartsWith("out ", StringComparison.Ordinal);

    private static string StripRef(string type) => IsByRef(type) ? type[4..] : type;
}
