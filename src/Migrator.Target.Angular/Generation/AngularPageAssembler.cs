using System.Text;
using System.Text.RegularExpressions;
using Migrator.Engine.Contracts;
using Migrator.Target.Core.Generation;
using Migrator.Target.Core.Translation;

namespace Migrator.Target.Angular.Generation;

/// <summary>
/// Writes a page the Angular way: a standalone component (class + `templateUrl`), the template, and the code-behind as a factory function
/// (`createXCode`) that holds the model, the handlers and the translated methods exactly as the React hook does. The component class only exposes what the
/// template uses. The model is a plain object: with zone.js, writes made in handlers show up without any proxy.
/// </summary>
public sealed partial class AngularPageAssembler : IPageAssembler
{
    /// <summary>Components @wfm/ui-angular has; anything else is a visible placeholder in the template.</summary>
    public static readonly HashSet<string> Supported = new(StringComparer.Ordinal)
    {
        "WfLabel", "WfButton", "WfLinkLabel", "WfTextBox", "WfComboBox", "WfCheckBox", "WfRadioButton", "WfNumericUpDown", "WfDateTimePicker",
        "WfProgress", "WfPictureBox", "WfUnsupported", "WfForm", "WfPanel", "WfGroupBox", "WfSplit", "WfSplitPane", "WfStatusBar",
        "WfTabs", "WfTabPage", "WfMenuBar", "WfMenuItem", "WfSeparator", "WfToolbar", "WfToolbarButton"
    };

    /// <summary>`HostPage` -> `host`, `ItemControlControl` -> `item-control-control`: the file and route base of a page.</summary>
    public static string FileBase(string component) =>
        JsxToAngular.Kebab(component.EndsWith("Page", StringComparison.Ordinal) && component.Length > 4 ? component[..^4] : component);

    public PageFiles Assemble(PageAssemblyInput input)
    {
        var fileBase = FileBase(input.Component);

        // Arity of the code-behind functions: a bare handler gets the event payload only when it takes one.
        var arity = FunctionRegex().Matches(string.Join("\n", input.HandlerCode))
            .ToDictionary(m => m.Groups["name"].Value, m => m.Groups["params"].Value.Split(',', StringSplitOptions.RemoveEmptyEntries).Length, StringComparer.Ordinal);
        var converter = new JsxToAngular(Supported, name => arity.TryGetValue(name, out var n) ? n : null);
        var template = converter.Convert(input.View);
        foreach (var tag in converter.Unsupported.Distinct())
            input.Issues.Add(new GenerationIssue(input.UnitName, "unsupported-control", $"{tag}: no component in @wfm/ui-angular yet; a placeholder is shown"));

        // Inline handlers lifted out of the markup become functions of the code-behind.
        var functions = new List<string>(input.HandlerCode);
        foreach (var h in converter.Inlines)
        {
            functions.Add($"{(h.IsAsync ? "async " : "")}function {h.Name}({string.Join(", ", h.Params.Select(p => $"{p.Name}: {p.Type}"))}) {{");
            foreach (var line in h.Body.Split('\n')) functions.Add("  " + line.TrimEnd('\r').TrimStart());
            functions.Add("}");
            functions.Add("");
        }

        var viewText = Regex.Replace(PageTranslator.StripStrings(string.Join("\n", input.View.Where(l => !l.TrimStart().StartsWith("//", StringComparison.Ordinal)))), @"/\*.*?\*/", "");
        var provided = new List<string>();
        if (input.UsesModel) provided.Add("vm");
        if (input.UsesFields) provided.Add("f");
        provided.AddRange(input.UsedProps.Select(p => p.Local));
        provided.AddRange(FunctionRegex().Matches(string.Join("\n", functions)).Select(m => m.Groups["name"].Value));
        var topLevelNames = input.TopLevel.Select(t => Regex.Match(t, @"^const (\w+)")).Where(m => m.Success).Select(m => m.Groups[1].Value).ToList();
        provided.AddRange(topLevelNames);
        var needed = provided.Distinct().Where(n => Regex.IsMatch(viewText, $@"(?<![\w.$]){Regex.Escape(n)}\b") || n.StartsWith("inline", StringComparison.Ordinal) && converter.Inlines.Any(i => i.Name == n)).ToList();
        var neededConsts = needed.Where(topLevelNames.Contains).ToList();
        var neededMembers = needed.Except(neededConsts).ToList();

        var code = BuildCode(input, functions, neededMembers.Where(n => n != "vm" && n != "f").ToList(), fileBase);
        var component = BuildComponent(input, converter.Components, neededMembers, neededConsts, fileBase);
        var view = new StringBuilder();
        view.AppendLine($"<!-- Generated by Migrator.Target.Angular from {input.UnitName} ({input.RelativePath}). Markup only: the code-behind (model, handlers, event wiring) is in {fileBase}.page.code.ts. Not final: see MIGRATION_REPORT.md. -->");
        foreach (var line in template) view.AppendLine(line);
        return new PageFiles(view.ToString(), code, component);
    }

    // ------------------------------------------------------------------------------------------------ code-behind

    private static string Prop(string name) => IdentifierRegex().IsMatch(name) ? name : "\"" + name.Replace("\"", "\\\"") + "\"";

    private string BuildCode(PageAssemblyInput input, List<string> functions, List<string> returned, string fileBase)
    {
        var props = input.CtorProps;
        var body = new List<string>();
        foreach (var t in input.TopLevel) body.Add(t.StartsWith("const ", StringComparison.Ordinal) ? "export " + t : t);
        if (input.TopLevel.Count > 0) body.Add("");
        if (props.Count > 0)
        {
            body.Add($"export interface {input.Component}Props {{");
            foreach (var p in props) body.Add($"  /** Constructor argument of the original form. */ {Prop(p.Key)}?: {p.Type};");
            body.Add("}");
            body.Add("");
        }
        body.Add("/** Event wiring of the original form (control.event -> handler). The template binds these handlers by name; kept here so the wiring is easy to trace back to the WinForms code-behind. */");
        body.Add("export const wiring = [");
        foreach (var w in input.Wiring)
            body.Add($"  {{ control: \"{w.Control}\", event: \"{w.Event}\", handler: \"{w.Handler}\", method: \"{w.Method}\", source: '{w.Source}' }},");
        body.Add("] as const;");
        body.Add("");

        var bindings = input.UsedProps.Select(p => (p.Key == p.Local ? p.Key : $"{p.Key}: {p.Local}") + (p.Default is null ? "" : $" = {p.Default}")).ToList();
        if (input.UsedProps.Any(p => p.Default?.Contains("fixtures.") == true))
            body.Add("// MOCK — constructor-argument defaults are fixture rows so the page opens on its own; the opener passes the real values");
        var factory = $"create{input.Component}Code";
        body.Add(bindings.Count > 0 ? $"export function {factory}(dialog: WfDialogService, {{ {string.Join(", ", bindings)} }}: {input.Component}Props) {{"
            : props.Count > 0 ? $"export function {factory}(dialog: WfDialogService, _props: {input.Component}Props) {{" : $"export function {factory}(dialog: WfDialogService) {{");
        foreach (var note in input.CtorNotes) body.Add($"  // TODO: constructor logic not translated: {note}");
        if (input.UsesModel)
        {
            foreach (var comment in input.ModelComments) body.Add("  " + comment);
            body.Add("  const vm = {");
            foreach (var entry in input.Model)
                body.Add($"    {Prop(entry.Id)}: {{ {string.Join(", ", entry.Props.Select(kv => kv.Value.StartsWith("@raw:", StringComparison.Ordinal) ? kv.Value[5..] : $"{kv.Key}: {kv.Value}"))} }},");
            body.Add("  };");
        }
        if (input.UsesFields)
        {
            body.Add("  // Fields of the original form. Initial values come from their C# initializers (a default for the declared type otherwise).");
            body.Add("  const f = {");
            foreach (var (name, initial) in input.FieldInitials) body.Add($"    {Prop(name)}: {initial},");
            body.Add("  };");
        }
        body.Add("");
        foreach (var line in functions) body.Add(line.Length == 0 ? "" : "  " + line);
        var members = new List<string>();
        if (input.UsesModel) members.Add("vm");
        if (input.UsesFields) members.Add("f");
        members.AddRange(returned.Where(n => FunctionNames(functions).Contains(n)));
        body.Add(members.Count > 0 ? $"  return {{ {string.Join(", ", members)} }};" : "  return {};");
        body.Add("}");

        // ---- imports, decided from the code this file really contains (still in the neutral form, where a page is opened as `<Page />`)
        string Strip(IEnumerable<string> lines) => Regex.Replace(PageTranslator.StripStrings(string.Join("\n", lines.Where(l => !l.TrimStart().StartsWith("//", StringComparison.Ordinal)))), @"/\*.*?\*/", "");
        var codeText = Strip(body);
        var sb = new StringBuilder();
        sb.AppendLine($"// Code-behind of {input.UnitName} ({input.RelativePath}), generated by Migrator.Target.Angular: model, handlers, translated methods and the event wiring table. The markup is in {fileBase}.page.html. Not final: see MIGRATION_REPORT.md.");
        var lib = new List<string> { "WfDialogService" };
        lib.AddRange(input.Lib.Where(n => char.IsLower(n[0]) && Regex.IsMatch(codeText, $@"(?<![\w.$]){Regex.Escape(n)}\b")));
        lib.AddRange(input.LibTypes.Where(t => Regex.IsMatch(codeText, $@"\b{Regex.Escape(t)}\b")).Select(t => "type " + t));
        sb.AppendLine($"import {{ {string.Join(", ", lib.Distinct())} }} from '@wfm/ui-angular';");
        foreach (var comp in input.PageImports.Where(p => Regex.IsMatch(codeText, $@"(?:<|\bwfDynamicControl\()\s*{Regex.Escape(p)}\b")))
            sb.AppendLine($"import {{ {comp} }} from './{FileBase(comp)}.page';");
        var helpers = CsharpRuntime.Helpers.Where(h => Regex.IsMatch(codeText, $@"\b{h}\(")).ToList();
        if (helpers.Count > 0) sb.AppendLine($"import {{ {string.Join(", ", helpers)} }} from '../lib/csharp';");
        var support = input.SupportClasses.Where(n => Regex.IsMatch(Strip(functions.Concat(input.FieldInitials.Select(f => f.Value)).Concat(props.Select(p => p.Type + " " + p.Default))), $@"(?<![\w.]){Regex.Escape(n)}\b")).OrderBy(n => n, StringComparer.Ordinal).ToList();
        if (support.Count > 0) sb.AppendLine($"import {{ {string.Join(", ", support)} }} from '../support';");
        if (input.NeedsFixtures) sb.AppendLine($"import {{ fixtures }} from '{input.FixturesImportPath}';");
        if (input.ServiceImport is not null && input.ServiceInstance.Length > 0 && Regex.IsMatch(codeText, $@"\b{Regex.Escape(input.ServiceInstance)}\."))
            sb.AppendLine(input.ServiceImport);
        var types = input.TypeImports.Where(t => Regex.IsMatch(codeText, $@"\b{Regex.Escape(t)}\b")).ToList();
        if (types.Count > 0) sb.AppendLine($"import type {{ {string.Join(", ", types)} }} from '{input.TypesImportPath}';");
        sb.AppendLine();

        // The translated code opens a page as `dialog.show(() => <Page />, ...)`; the Angular service takes the component class itself.
        foreach (var line in body) sb.AppendLine(DialogShow().Replace(line, "$1"));
        return sb.ToString();
    }

    private static HashSet<string> FunctionNames(IEnumerable<string> functions) =>
        FunctionRegex().Matches(string.Join("\n", functions)).Select(m => m.Groups["name"].Value).ToHashSet(StringComparer.Ordinal);

    // ------------------------------------------------------------------------------------------------ component

    private string BuildComponent(PageAssemblyInput input, IEnumerable<string> components, List<string> members, List<string> consts, string fileBase)
    {
        var hasProps = input.CtorProps.Count > 0;
        var imports = components.OrderBy(c => c, StringComparer.Ordinal).ToList();
        var sb = new StringBuilder();
        sb.AppendLine($"// Generated by Migrator.Target.Angular from {input.UnitName} ({input.RelativePath}). The component only exposes what the template uses; the logic is in {fileBase}.page.code.ts. Not final: see MIGRATION_REPORT.md.");
        sb.AppendLine($"import {{ Component, {(hasProps ? "OnInit, input, " : "")}inject }} from '@angular/core';");
        sb.AppendLine($"import {{ {string.Join(", ", new[] { "WfDialogService" }.Concat(imports))} }} from '@wfm/ui-angular';");
        var fromCode = new List<string> { $"create{input.Component}Code" };
        fromCode.AddRange(consts);
        if (hasProps) fromCode.Add($"type {input.Component}Props");
        sb.AppendLine($"import {{ {string.Join(", ", fromCode)} }} from './{fileBase}.page.code';");
        sb.AppendLine();
        sb.AppendLine("@Component({");
        sb.AppendLine($"  selector: 'app-{fileBase}',");
        sb.AppendLine("  standalone: true,");
        sb.AppendLine($"  imports: [{string.Join(", ", imports)}],");
        sb.AppendLine($"  templateUrl: './{fileBase}.page.html',");
        sb.AppendLine("})");
        sb.AppendLine($"export class {input.Component}{(hasProps ? " implements OnInit" : "")} {{");
        sb.AppendLine("  private readonly dialog = inject(WfDialogService);");
        if (hasProps)
        {
            foreach (var p in input.CtorProps) sb.AppendLine($"  /** Constructor argument of the original form. */\n  readonly {Prop(p.Key)} = input<{input.Component}Props['{p.Key}']>();");
            sb.AppendLine($"  private code!: ReturnType<typeof create{input.Component}Code>;");
            sb.AppendLine("  protected ready = false;");
            sb.AppendLine();
            sb.AppendLine("  ngOnInit(): void {");
            sb.AppendLine($"    this.code = create{input.Component}Code(this.dialog, {{ {string.Join(", ", input.CtorProps.Select(p => $"{Prop(p.Key)}: this.{p.Key}()"))} }});");
            sb.AppendLine("    this.ready = true;");
            sb.AppendLine("  }");
        }
        else sb.AppendLine($"  private readonly code = create{input.Component}Code(this.dialog);");
        foreach (var name in members) sb.AppendLine($"  protected get {name}() {{ return this.code.{name}; }}");
        foreach (var name in consts) sb.AppendLine($"  protected readonly {name} = {name};");
        sb.AppendLine("}");
        return sb.ToString();
    }

    [GeneratedRegex(@"^(?:async )?function (?<name>\w+)\((?<params>[^)]*)\)", RegexOptions.Multiline)]
    private static partial Regex FunctionRegex();

    [GeneratedRegex(@"^[A-Za-z_$][\w$]*$")]
    private static partial Regex IdentifierRegex();

    [GeneratedRegex(@"\(\)\s*=>\s*<(\w+)\s*/>")]
    private static partial Regex DialogShow();
}
